 ### 2️⃣ Variables in Python 🛠  

 # Assigning values to variables is straightforward in Python. You can use the assignment operator (=) to assign a value to a variable.

name = "Alice"
age = 30
height = 5.7

# Printing the values of the variables
print(name)
print(age)
print(height)


# String
greeting = "Hello, World!"

# Integer
year = 2024

# Float
pi = 3.14159

# Boolean
is_active = True

print(greeting)  # Output: Hello, World!
print(year)      # Output: 2024
print(pi)        # Output: 3.14159
print(is_active) # Output: True



count = 10
count += 1  # Increment by 1
print(count)  # Output: 11
